import { Download } from 'lucide-react';
import Button from '../buttons/Button.jsx';
import { money, monthLabel } from '../../utils/format.js';
import { download } from '../../utils/csv.js';
import { companySettings } from '../../data/departments.js';
import { useToast } from '../../context/ToastContext.jsx';

export default function PayslipCard({ slip }) {
  const toast = useToast();
  const lines = [['Basic salary', slip.basic], ['House rent allowance', slip.hra], ['Medical allowance', slip.medical], ['Other allowances', slip.other]];
  const ded = [['Provident fund', slip.pf], ['Income tax', slip.tax]];
  // Placeholder: a real PDF will be generated by the backend.
  const save = () => {
    const text = [`${companySettings.companyName} — Payslip ${monthLabel(slip.month)}`, `${slip.employee.name} (${slip.employee.id})`, ...lines.map(([l, v]) => `${l}: ${money(v)}`), `Gross: ${money(slip.gross)}`, ...ded.map(([l, v]) => `${l}: ${money(v)}`), `Net: ${money(slip.net)}`].join('\n');
    download(`payslip-${slip.month}-${slip.employee.id}.txt`, text, 'text/plain');
    toast.success('Payslip downloaded (placeholder file).');
  };
  return (
    <div>
      <div className="payslip">
        <div className="row between" style={{ alignItems: 'flex-start' }}>
          <div><h2 style={{ fontSize: 18 }}>{companySettings.companyName}</h2><p className="muted small">{companySettings.officeLocation}</p></div>
          <div className="right"><strong>Payslip</strong><p className="muted small">{monthLabel(slip.month)}</p></div>
        </div>
        <dl className="kv" style={{ margin: '18px 0' }}>
          <div><dt>Employee</dt><dd>{slip.employee.name}</dd></div><div><dt>Employee ID</dt><dd>{slip.employee.id}</dd></div>
          <div><dt>Department</dt><dd>{slip.employee.department}</dd></div><div><dt>Designation</dt><dd>{slip.employee.designation}</dd></div>
        </dl>
        <table><tbody>
          {lines.map(([l, v]) => <tr key={l}><td>{l}</td><td className="right">{money(v)}</td></tr>)}
          <tr className="tot"><td>Gross salary</td><td className="right">{money(slip.gross)}</td></tr>
          {ded.map(([l, v]) => <tr key={l}><td>{l}</td><td className="right">− {money(v)}</td></tr>)}
          <tr className="tot"><td>Net salary</td><td className="right">{money(slip.net)}</td></tr>
        </tbody></table>
      </div>
      <div className="row no-print" style={{ justifyContent: 'flex-end', padding: '12px 0 0' }}><Button variant="primary" icon={Download} onClick={save}>Download PDF</Button></div>
    </div>
  );
}
